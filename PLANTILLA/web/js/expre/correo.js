const inputCorreo = document.getElementById("correo");
const errorCorreo = document.getElementById("errorCorreo");

function validarCorreo(){
    const valor = inputCorreo.value.trim();

    if (valor.length === 0) {
        errorCorreo.textContent = 'El correo es obligatorio';
        errorCorreo.classList.remove('d-none');
        return false;
    }
    if (valor.length < 3) {
        errorCorreo.textContent = 'El correo debe tener un minimo de 3 caracteres';
        errorCorreo.classList.remove('d-none');
        return false;
    }
    if (!correo.test(valor)) {
        errorCorreo.textContent = 'Formato de correo invalido';
        errorCorreo.classList.remove('d-none');
        return false;
    }

    errorCorreo.classList.add('d-none');
    return true;
}